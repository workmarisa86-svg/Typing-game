#!/usr/bin/env python3
"""Build data/verses-en.js and data/verses-es.js from the public-domain CSV sources.

Verse text is copied exactly as it appears in the source files; this script only chooses
which verses to include. Run from the repository root:  python3 tools/build_verses.py
"""
import csv, json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BOOKS = ['Psalms', 'Proverbs', 'Ecclesiastes', 'Isaiah', 'Matthew', 'John', 'Romans',
         'I Corinthians', 'Galatians', 'Ephesians', 'Philippians', 'Colossians', 'James', 'I John']
NAMES = {
    'en': ['Psalm', 'Proverbs', 'Ecclesiastes', 'Isaiah', 'Matthew', 'John', 'Romans',
           '1 Corinthians', 'Galatians', 'Ephesians', 'Philippians', 'Colossians', 'James', '1 John'],
    'es': ['Salmos', 'Proverbios', 'Eclesiastés', 'Isaías', 'Mateo', 'Juan', 'Romanos',
           '1 Corintios', 'Gálatas', 'Efesios', 'Filipenses', 'Colosenses', 'Santiago', '1 Juan'],
}
# characters a US / US-International keyboard can type
OK = set(chr(c) for c in range(32, 127)) | set('áéíóúüñÁÉÍÓÚÜÑ¿¡')
BAD = set('[]{}<>')

def build(src, lang, version, var):
    rows = []
    with open(os.path.join(ROOT, 'data', 'sources', src), encoding='utf-8', newline='') as f:
        for r in csv.DictReader(f):
            if r['Book'] not in BOOKS:
                continue
            text = r['Text']
            if int(r['Verse']) == 1:      # chapter openings carry heading/capitalisation artefacts
                continue
            if not (25 <= len(text) <= 230):
                continue
            if any(ch not in OK or ch in BAD for ch in text):
                continue
            rows.append([BOOKS.index(r['Book']), int(r['Chapter']), int(r['Verse']), text])
    data = {'version': version, 'books': NAMES[lang], 'v': rows}
    out = os.path.join(ROOT, 'data', 'verses-%s.js' % lang)
    with open(out, 'w', encoding='utf-8') as f:
        f.write('/* Generated by tools/build_verses.py from data/sources/%s — do not edit by hand. */\n' % src)
        f.write('window.%s = %s;\n' % (var, json.dumps(data, ensure_ascii=False, separators=(',', ':'))))
    print(out, len(rows), 'verses')

build('KJV.csv', 'en', 'KJV', 'VERSES_EN')
build('SpaRV1909.csv', 'es', 'RV 1909', 'VERSES_ES')
